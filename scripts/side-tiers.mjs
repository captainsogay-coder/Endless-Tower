// Measures every unit's side tiers and writes src/units/sideTiers.data.js.
//
//   node scripts/side-tiers.mjs          re-measure everything and write the table
//   node scripts/side-tiers.mjs --check  exit 1 if any unit changed since the last run
//
// See src/meta/sideTierBench.js for what each category measures.
import { writeFileSync } from 'node:fs';
import { registerRoster, ROSTER as RAW } from '../src/units/roster.js';
import { getUnit } from '../src/units/unitRegistry.js';
import { benchContext, measureUnit, BENCH } from '../src/meta/sideTierBench.js';
import { unitSignature, balanceSignature, isStale } from '../src/meta/sideTiers.js';

registerRoster();
const ROSTER = RAW.map((d) => getUnit(d.id)); // the registered (normalised) definitions
const check = process.argv.includes('--check');
if (check) {
  const stale = ROSTER.filter(isStale).map((d) => d.id);
  if (stale.length) {
    console.error(`side tiers are out of date for: ${stale.join(', ')}\nrun: npm run ratings`);
    process.exit(1);
  }
  console.log(`side tiers up to date for all ${ROSTER.length} units`);
  process.exit(0);
}

const t0 = Date.now();
const ctx = benchContext();
const units = {};
for (const def of ROSTER) {
  const m = measureUnit(def, ctx);
  units[def.id] = { sig: unitSignature(def), ratings: m.ratings, raw: m.raw };
}
const data = { version: 1, balance: balanceSignature(), refDps: Math.round(ctx.refDps * 100) / 100, bench: { wave: BENCH.wave, level: 0 }, units };
const body = Object.entries(units)
  .map(([id, u]) => `    ${JSON.stringify(id)}: ${JSON.stringify(u)},`)
  .join('\n');
writeFileSync(
  new URL('../src/units/sideTiers.data.js', import.meta.url),
  `// GENERATED by scripts/side-tiers.mjs (npm run ratings) – do not edit by hand.
// Measured side tiers for every unit; see src/meta/sideTierBench.js.
export const SIDE_TIER_DATA = {
  version: ${data.version},
  balance: ${JSON.stringify(data.balance)},
  refDps: ${data.refDps},
  bench: ${JSON.stringify(data.bench)},
  units: {
${body}
  },
};
`,
);
console.log(`measured ${ROSTER.length} units in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
